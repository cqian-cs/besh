"""``besh serve``：在当前目录生成并运行信标。

生成的文件与 README 的约定一致：

* ``./besh_beacon.py`` —— 信标主程序，运行它即为服务端（sqless app）
* ``./www/index.html`` —— Web 操作界面（WebShell + 文件上传下载）
* ``./db`` ``./fs``    —— sqless 的数据库与文件目录
"""

from __future__ import annotations

import os
import secrets
import subprocess
import sys
import time
from typing import Optional

from .__about__ import __version__
from .util import DEFAULT_PORT, BeshError, getenv, getenv_int

APP_FILE = "besh_beacon.py"
SECRET_FILE = ".besh_secret"
WEB_MARKER = "<!-- generated by besh"

TEMPLATE = '''# -*- coding: utf-8 -*-
"""besh beacon —— 信标服务端（由 `besh serve` 生成，可直接修改）。

按 README 的约定：本文件是主程序，运行它即为服务端。

    export besh_secret=CHANGE_TO_YOUR_PASSWORD
    python3 besh_beacon.py

真正的逻辑在 besh.beacon 里。所有 @sqless.api 函数会同时暴露成
HTTP 接口（/api/*）和 MCP 工具（/mcp），遥控器 / Web / AI Agent 共用一套入口。
"""

import asyncio
import os
import sys

import sqless

try:
    import besh.beacon as beacon
except ImportError:  # pragma: no cover
    sys.exit("缺少依赖：pip install besh")

# 路径都相对于本文件所在目录；host/port/secret 可被同名环境变量覆盖
cfg = beacon.make_cfg(__file__)
dbs = sqless.DBS(cfg["path_base_db"])

# 注册状态存储与 API 函数
beacon.bind(cfg, dbs)


async def on_init():
    beacon.startup()


async def on_close():
    beacon.shutdown()


if __name__ == "__main__":
    print("besh beacon starting ...")
    asyncio.run(sqless.run_server(__file__))
'''


def ensure_secret(path_this: str, secret: Optional[str] = None) -> str:
    """密钥优先级：命令行 > 环境变量 > .besh_secret 文件 > 新生成。"""
    if secret:
        return secret.strip()
    env = getenv("besh_secret")
    if env:
        return env.strip()
    path = os.path.join(path_this, SECRET_FILE)
    if os.path.isfile(path):
        try:
            with open(path, "r", encoding="utf-8") as f:
                value = f.read().strip()
            if value:
                return value
        except OSError:  # pragma: no cover
            pass
    value = secrets.token_urlsafe(12)
    with open(path, "w", encoding="utf-8") as f:
        f.write(value + "\n")
    try:
        os.chmod(path, 0o600)
    except OSError:  # pragma: no cover - Windows
        pass
    print(f"已生成密钥并写入 {path}（请妥善保管）")
    return value


def write_app(path_this: str, reset: bool = False) -> str:
    path = os.path.join(path_this, APP_FILE)
    if os.path.exists(path) and not reset:
        return path
    if os.path.exists(path):
        backup = f"{os.path.splitext(path)[0]}_bk-{time.strftime('%Y%m%d-%H%M%S')}.py"
        os.replace(path, backup)
        print(f"已备份旧文件到 {os.path.basename(backup)}")
    with open(path, "w", encoding="utf-8") as f:
        f.write(TEMPLATE)
    print(f"已生成 {APP_FILE}")
    return path


def webui_html() -> str:
    """内置 Web 界面（优先读包内的 www/index.html）。"""
    try:
        from importlib.resources import files

        resource = files("besh").joinpath("www/index.html")
        if resource.is_file():
            return resource.read_text(encoding="utf-8")
    except Exception:  # pragma: no cover - 老版本 Python / 打包异常
        pass
    here = os.path.join(os.path.dirname(os.path.abspath(__file__)), "www", "index.html")
    with open(here, "r", encoding="utf-8") as f:
        return f.read()


def write_web(path_this: str, force: bool = False) -> str:
    """写 Web 界面；用户改过的文件不覆盖（除非 --force）。"""
    www = os.path.join(path_this, "www")
    os.makedirs(www, exist_ok=True)
    path = os.path.join(www, "index.html")
    html = webui_html()
    if os.path.exists(path) and not force:
        try:
            with open(path, "r", encoding="utf-8") as f:
                head = f.read(200)
        except OSError:  # pragma: no cover
            head = ""
        if WEB_MARKER not in head:
            return path  # 用户自己改过，保留
    with open(path, "w", encoding="utf-8") as f:
        f.write(html)
    return path


def serve(
    base_dir: Optional[str] = None,
    host: Optional[str] = None,
    port: Optional[int] = None,
    secret: Optional[str] = None,
    reset: bool = False,
    force_web: bool = False,
    no_run: bool = False,
) -> int:
    path_this = os.path.abspath(base_dir or os.getcwd())
    os.makedirs(path_this, exist_ok=True)
    host = host or getenv("besh_host", default="0.0.0.0") or "0.0.0.0"
    port = int(port or getenv_int("besh_port", default=DEFAULT_PORT))
    secret = ensure_secret(path_this, secret)

    app_path = write_app(path_this, reset=reset)
    web_path = write_web(path_this, force=force_web)

    shown_host = "127.0.0.1" if host in ("0.0.0.0", "::") else host
    url = f"http://{shown_host}:{port}/?secret={secret}"
    print("=" * 72)
    print(f"besh beacon v{__version__}")
    print(f"  工作目录 : {path_this}")
    print(f"  主程序   : {os.path.basename(app_path)}")
    print(f"  Web 界面 : {os.path.relpath(web_path, path_this)}")
    print(f"  工人连接 : export besh_url=http://<HOST>:{port}?secret={secret}")
    print(f"  浏览器   : {url}")
    print(f"  MCP      : http://<HOST>:{port}/mcp  (Authorization: Bearer <secret>)")
    print("=" * 72)

    if no_run:
        return 0

    env = dict(os.environ)
    env["besh_host"] = host
    env["besh_port"] = str(port)
    env["besh_secret"] = secret
    try:
        return subprocess.call([sys.executable, app_path], cwd=path_this, env=env)
    except KeyboardInterrupt:
        return 0
    except OSError as exc:  # pragma: no cover
        raise BeshError(f"启动信标失败：{exc}") from None
