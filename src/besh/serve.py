"""``besh serve``：在当前目录生成并运行信标。

生成的文件与 README 的约定一致：

* ``./besh_beacon.py`` —— 信标主程序，运行它即为服务端（sqless app）
* ``./www/index.html`` —— Web 操作界面（WebShell + 文件上传下载）
* ``./.env``           —— 环境变量（密钥）

运行时状态全部在内存里，不会生成 db/fs 目录，也不会写任何数据文件。
"""

from __future__ import annotations

import os
import re
import secrets
import subprocess
import sys
import time
from typing import Optional, Tuple

from .__about__ import __version__
from .util import DEFAULT_PORT, BeshError, getenv, getenv_int, load_env

APP_FILE = "besh_beacon.py"
ENV_FILE = ".env"
WEB_MARKER = "<!-- generated by besh"

# 入口程序顶部的配置段（直接编辑这两个值即可改 IP / 端口）
CFG_HOST_RE = re.compile(r'^CFG_HOST\s*=\s*"[^"]*"', re.M)
CFG_PORT_RE = re.compile(r"^CFG_PORT\s*=\s*\d+", re.M)
CFG_HOST_LINE = 'CFG_HOST = "{host}"'
CFG_PORT_LINE = "CFG_PORT = {port}"

TEMPLATE = '''# -*- coding: utf-8 -*-
"""besh beacon —— 信标服务端（由 `besh serve` 生成）。

入口程序就是配置文件：直接修改下面的 CFG_HOST / CFG_PORT，
改完重启本文件即可生效。你也可以在本文件里追加自己的
@sqless.api 函数，它们会自动变成 HTTP 接口和 MCP 工具。

    python3 besh_beacon.py

密钥等环境变量存放在同目录的 .env 文件里（自动加载，可直接编辑）。
真正的逻辑在 besh.beacon 里。所有 @sqless.api 函数会同时暴露成
HTTP 接口（/api/*）和 MCP 工具（/mcp），遥控器 / Web / AI Agent 共用一套入口。
"""

import asyncio
import os
import sys

import sqless

try:
    import besh.beacon as beacon
except ImportError:  # pragma: no cover
    sys.exit("缺少依赖：pip install besh")

# ============ 配置（直接改这里，改完重启生效） ============
CFG_HOST = "__CFG_HOST__"   # 监听地址；"0.0.0.0" 表示所有网卡
CFG_PORT = __CFG_PORT__     # 监听端口
# =========================================================

# 信标状态全部在内存里（见 besh/store.py），这里不创建任何数据库文件。
# sqless 的 /db、/fs 接口本项目用不到，置空即可，避免误触时落盘。
dbs = None

cfg = beacon.make_cfg(__file__, host=CFG_HOST, port=CFG_PORT)

# 注册状态存储与 API 函数
beacon.bind(cfg, dbs)


async def on_init():
    beacon.startup()


async def on_close():
    beacon.shutdown()


if __name__ == "__main__":
    print("besh beacon starting ...")
    asyncio.run(sqless.run_server(__file__))
'''


def ensure_secret(path_this: str, secret: Optional[str] = None) -> str:
    """密钥优先级：命令行 > 环境变量 > .env 文件 > 新生成并写进 .env。"""
    if secret:
        return secret.strip()
    env = getenv("besh_secret")
    if env:
        return env.strip()
    path = os.path.join(path_this, ENV_FILE)
    if os.path.isfile(path):
        # .env 已存在：加载它；里面没有 besh_secret 就追加一条
        load_env(path_this)
        env = getenv("besh_secret")
        if env:
            return env.strip()
        value = secrets.token_urlsafe(12)
        with open(path, "a", encoding="utf-8") as f:
            f.write(f"besh_secret={value}\n")
        _chmod_private(path)
        print(f"已在 {ENV_FILE} 中追加 besh_secret（请妥善保管）")
        return value
    value = secrets.token_urlsafe(12)
    content = (
        "# besh 信标环境变量（besh serve / python besh_beacon.py 会自动加载，改完重启生效）\n"
        "# 注意：本文件含密钥，不要提交到 git\n"
        "# 监听地址/端口不在这里——它们写在 besh_beacon.py 顶部（CFG_HOST / CFG_PORT）\n"
        "besh_secret=" + value + "\n"
    )
    with open(path, "w", encoding="utf-8") as f:
        f.write(content)
    _chmod_private(path)
    print(f"已生成 {ENV_FILE}（含 besh_secret，请妥善保管，不要提交到 git）")
    return value


def _chmod_private(path: str) -> None:
    try:
        os.chmod(path, 0o600)
    except OSError:  # pragma: no cover - Windows
        pass


def write_app(
    path_this: str,
    reset: bool = False,
    host: str = "0.0.0.0",
    port: int = DEFAULT_PORT,
) -> Tuple[str, bool]:
    """生成入口程序 besh_beacon.py，把 host/port 写进文件（入口程序即配置文件）。

    返回 (路径, 是否新建)。文件已存在时不动它（保护用户手改的配置），
    需要改配置请用 :func:`patch_cfg` 或 ``--reset`` 重新生成。
    """
    path = os.path.join(path_this, APP_FILE)
    if os.path.exists(path) and not reset:
        return path, False
    if os.path.exists(path):
        backup = f"{os.path.splitext(path)[0]}_bk-{time.strftime('%Y%m%d-%H%M%S')}.py"
        os.replace(path, backup)
        print(f"已备份旧文件到 {os.path.basename(backup)}")
    body = TEMPLATE.replace("__CFG_HOST__", str(host)).replace(
        "__CFG_PORT__", str(int(port))
    )
    with open(path, "w", encoding="utf-8") as f:
        f.write(body)
    print(f"已生成 {APP_FILE}（配置写在文件顶部，可直接修改）")
    return path, True


def read_cfg(path: str) -> Tuple[str, int]:
    """读入口程序顶部的 CFG_HOST / CFG_PORT（解析失败时用默认值兜底）。"""
    try:
        with open(path, "r", encoding="utf-8") as f:
            text = f.read(4096)
    except OSError:  # pragma: no cover
        return "0.0.0.0", DEFAULT_PORT
    m_host = re.search(r'^CFG_HOST\s*=\s*"([^"]*)"', text, re.M)
    m_port = re.search(r"^CFG_PORT\s*=\s*(\d+)", text, re.M)
    host = m_host.group(1) if m_host else getenv("besh_host") or "0.0.0.0"
    port = int(m_port.group(1)) if m_port else (getenv_int("besh_port") or DEFAULT_PORT)
    return host or "0.0.0.0", port


def patch_cfg(path: str, host: Optional[str] = None, port: Optional[int] = None) -> None:
    """把命令行指定的 host/port 原地写进入口程序（已存在时的 --host/--port 走这里）。"""
    with open(path, "r", encoding="utf-8") as f:
        text = f.read()
    if host:
        text = CFG_HOST_RE.sub(CFG_HOST_LINE.format(host=host), text, count=1)
    if port:
        text = CFG_PORT_RE.sub(CFG_PORT_LINE.format(port=int(port)), text, count=1)
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)


def webui_html() -> str:
    """内置 Web 界面（优先读包内的 www/index.html）。"""
    try:
        from importlib.resources import files

        resource = files("besh").joinpath("www/index.html")
        if resource.is_file():
            return resource.read_text(encoding="utf-8")
    except Exception:  # pragma: no cover - 老版本 Python / 打包异常
        pass
    here = os.path.join(os.path.dirname(os.path.abspath(__file__)), "www", "index.html")
    with open(here, "r", encoding="utf-8") as f:
        return f.read()


def write_web(path_this: str, force: bool = False) -> str:
    """写 Web 界面；用户改过的文件不覆盖（除非 --force）。"""
    www = os.path.join(path_this, "www")
    os.makedirs(www, exist_ok=True)
    path = os.path.join(www, "index.html")
    html = webui_html()
    if os.path.exists(path) and not force:
        try:
            with open(path, "r", encoding="utf-8") as f:
                head = f.read(200)
        except OSError:  # pragma: no cover
            head = ""
        if WEB_MARKER not in head:
            return path  # 用户自己改过，保留
    with open(path, "w", encoding="utf-8") as f:
        f.write(html)
    return path


def serve(
    base_dir: Optional[str] = None,
    host: Optional[str] = None,
    port: Optional[int] = None,
    secret: Optional[str] = None,
    reset: bool = False,
    force_web: bool = False,
    no_run: bool = False,
) -> int:
    path_this = os.path.abspath(base_dir or os.getcwd())
    os.makedirs(path_this, exist_ok=True)
    load_env(path_this)  # 加载已有的 .env（不覆盖真实环境变量）
    fresh_host = host or getenv("besh_host") or "0.0.0.0"
    fresh_port = int(port or getenv_int("besh_port") or DEFAULT_PORT)
    secret = ensure_secret(path_this, secret)
    app_path, created = write_app(path_this, reset=reset, host=fresh_host, port=fresh_port)
    if not created and (host or port):
        patch_cfg(app_path, host=host, port=port)
        print(f"已更新 {os.path.basename(app_path)} 中的配置")
    web_path = write_web(path_this, force=force_web)

    host, port = read_cfg(app_path)
    shown_host = "127.0.0.1" if host in ("0.0.0.0", "::") else host
    url = f"http://{shown_host}:{port}/?secret={secret}"
    print("=" * 72)
    print(f"besh beacon v{__version__}")
    print(f"  工作目录 : {path_this}")
    print(f"  主程序   : {os.path.basename(app_path)}（CFG_HOST={host} CFG_PORT={port}）")
    print(f"  环境变量 : {ENV_FILE}（含 besh_secret，自动加载，可直接编辑）")
    print(f"  Web 界面 : {os.path.relpath(web_path, path_this)}")
    print(f"  工人连接 : export besh_url=http://<HOST>:{port}?secret={secret}")
    print(f"  浏览器   : {url}")
    print(f"  MCP      : http://<HOST>:{port}/mcp  (Authorization: Bearer <secret>)")
    print("=" * 72)

    if no_run:
        return 0

    env = dict(os.environ)
    env["besh_secret"] = secret
    try:
        return subprocess.call([sys.executable, app_path], cwd=path_this, env=env)
    except KeyboardInterrupt:
        return 0
    except OSError as exc:  # pragma: no cover
        raise BeshError(f"启动信标失败：{exc}") from None
